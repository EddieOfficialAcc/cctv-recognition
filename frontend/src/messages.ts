export const messages: Record<Language, Messages> = {
  en: english, 'zh-Hant': traditional, 'zh-Hans': simplified,
}

export function isLanguage(value: unknown): value is Language {
  return value === 'en' || value === 'zh-Hant' || value === 'zh-Hans'
}

export function translate(language: Language, key: MessageKey, parameters: Record<string, string | number> = {}) {
  return messages[language][key].replace(/\{(\w+)\}/g, (_, name: string) => {
    if (!(name in parameters)) throw new Error(`Missing translation parameter: ${key}.${name}`)
    return String(parameters[name])
  })
}
